# Python Operators---
# Operators are used to perform operations on variables and values.
# Python provides several types of operators:
    # 1. Arithmetic Operators
    # 2. Assignment Operators
    # 3. Comparison Operators
    # 4. Logical Operators
    # 5. Identity Operators
    # 6. Membership Operators
    # 7. Bitwise Operators



# Arithmetic Operators--------------
# Used to perform mathematical operations.

a = 20
b = 26

print(a + b)    # Addition
print(a - b)    # Subtraction
print(a * b)    # Multiplication
print(a / b)    # Division
print(a % b)    # Modulus
print(a ** b)   # Exponentiation
print(a // b)   # Floor Division




# Assignment Operators -----------
# Used to assign values to variables.

print(f"Hi Now working with Assignment")
x = 10
print(x)


# Addition Assignment
x += 5 # same as (x = x+5)
print(x)


# Subtraction Assignment
x -= 3  # same as (x = x-3)
print(x)


# Multiplication Assignment
x *= 2  # same as (x = x*2)
print(x)


# Division Assignment
x /= 4 # same as (x = x/4)
print(x)


# Modulus Assignment
x %= 3
print(x)


# Exponentiation Assignment
x = 2
x **= 3
print(x)


# Floor Division Assignment
x = 10
x //= 3
print(x)


# Other Assignment Operators
x = 10
print(x)
x &= 3      # Bitwise AND assignment
print(x)
x |= 3      # Bitwise OR assignment
print(x)
x ^= 3      # Bitwise XOR assignment
print(x)
x >>= 1     # Right shift assignment
print(x)
x <<= 1     # Left shift assignment
print(x)


