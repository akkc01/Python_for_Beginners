# A while loop executes as long as the condition is True.


# Basic while Loop

count = 1

while count <= 5:
    print(count)
    count += 1


# Output:
# 1
# 2
# 3
# 4
# 5


# while Loop with User Input

number = int(input("Enter a number: "))

while number > 0:
    print(number)
    number -= 1

