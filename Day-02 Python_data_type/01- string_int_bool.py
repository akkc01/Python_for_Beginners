# Python Data Types--

# Data types define the type of value stored in a variable.
# Python has several built-in data types.


# 1. String (str)
# Used to store text.

name = "Amit"
city = 'Pune'

print(name)
print(city)
print(type(name))


# 2. Integer (int)
# Used to store whole numbers.

age = 30
count = 100
negative_number = -50

print(age)
print(count)
print(negative_number)
print(type(age))


# 3. Float (float)
# Used to store decimal numbers.

salary = 75000.50
percentage = 95.5
temperature = -10.5

print(salary)
print(percentage)
print(temperature)
print(type(salary))


# 4. Complex (complex)
# Used to store complex numbers.
# A complex number contains a real and an imaginary part.

number = 3 + 5j

print(number)
print(type(number))


# 5. Boolean (bool)
# Used to represent True or False.

is_active = True
is_deleted = False

print(is_active)
print(is_deleted)
print(type(is_active))

